const { chromium } = require('playwright');
const path = require('path'), fs = require('fs'), os = require('os');
const EXT = path.join(__dirname, '..', 'dist', 'chrome-extension');
const src = fs.readFileSync(path.join(__dirname, 'group-test.js'), 'utf8');
const page = eval(src.match(/const page = (`[\s\S]*?`);/)[1]);
(async () => {
  const ctx = await chromium.launchPersistentContext(fs.mkdtempSync(path.join(os.tmpdir(), 'd-')), { channel: 'chromium', headless: true, args: [`--disable-extensions-except=${EXT}`, `--load-extension=${EXT}`] });
  await ctx.route(/^https?:/, r => r.request().url().startsWith('https://www.fallenlondon.com') ? r.fulfill({ contentType: 'text/html', body: page }) : r.fulfill({ contentType: 'application/json', body: '{}' }));
  const p = await ctx.newPage(); p.on('pageerror', e => console.log('PAGEERROR', e.message));
  await p.setViewportSize({ width: 390, height: 780 });
  await p.goto('https://www.fallenlondon.com/'); await p.waitForTimeout(500);
  const bar = p.locator('#flc-host >> .fabbar'), box = () => bar.boundingBox();
  const closed = () => p.locator('#flc-host >> .overlay').evaluate(e => e.classList.contains('hidden'));
  console.log('start', await box());
  await p.screenshot({ path: path.join(__dirname, 'drag-before.png') });
  const fab = await p.locator('#flc-host >> .fab').boundingBox();
  await p.mouse.move(fab.x + 10, fab.y + 10); await p.mouse.down();
  for (let i = 1; i <= 10; i++) await p.mouse.move(fab.x + 10 - 15 * i, fab.y + 10 - 40 * i);
  await p.mouse.up(); await p.waitForTimeout(100);
  console.log('after drag', await box(), '| panel still closed:', await closed(), '| recording unchanged:', await p.evaluate(() => window.__FLC_API.isRecording()));
  const g = await p.locator('#flc-host >> .fabgrip').boundingBox();
  await p.mouse.move(g.x + 5, g.y + 5); await p.mouse.down(); await p.mouse.move(-500, 2000, { steps: 5 }); await p.mouse.up();
  console.log('dragged off-screen, clamped to:', await box());
  await p.reload(); await p.waitForTimeout(500);
  console.log('after reload', await box());
  await p.locator('#flc-host >> .fab').click(); await p.waitForTimeout(200);
  console.log('plain tap still opens panel:', !(await closed()));
  await p.locator('#flc-host >> button[data-h="settings"]').click();
  await p.locator('#flc-host >> input[data-k="compactFab"]').check();
  await p.locator('#flc-host >> button[data-s="fabreset"]').click(); await p.waitForTimeout(100);
  await p.locator('#flc-host >> button[data-h="close"]').click();
  console.log('compact + reset', await box(), '| labels hidden:', await p.locator('#flc-host >> .fab .lbl').isHidden());
  await p.screenshot({ path: path.join(__dirname, 'drag-after.png') });
  await ctx.close();
})();
